// Initialise a copy of this boilerplate for a real project. No dependencies, no network.
//   node scripts/claude/init-project.mjs --name "Acme Portal" --jira-key ACME --stack nestjs-backend
// Options: --description "..." --default-branch main --roadmap "docs/SOW.md" --stack nestjs-backend|generic
//          --install/--build/--lint/--test/--verify "<command>"  --force  --reset-profile  --dry-run  --root <dir>
// --force runs init again but never discards a filled-in .claude/project-profile.md. Only --reset-profile does (it works with or
// without --force), and the old file is kept as project-profile.md.bak (a later reset keeps a timestamped copy).
// Arrays in hooks.config.json (policyFiles, immutableDirs, ...) are merged, not replaced.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const flag = (n) => args.includes(`--${n}`);
const opt = (n, d) => {
  const i = args.indexOf(`--${n}`);
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : d;
};

const root = path.resolve(opt('root', path.resolve(here, '..', '..')));
const dry = flag('dry-run');
const force = flag('force');
const STACK_ALIASES = { nestjs: 'nestjs-backend', react: 'react-nextjs', nextjs: 'react-nextjs', frontend: 'react-nextjs' };
const stackArg = opt('stack', 'generic');
const stack = STACK_ALIASES[stackArg] ?? stackArg;
const name = opt('name');
const jiraKey = opt('jira-key', 'PROJ').toUpperCase();

const fail = (m) => {
  console.error(`ERROR ${m}`);
  process.exit(1);
};
if (!name) fail('--name "<Project Name>" is required');
if (!/^[A-Z][A-Z0-9]+$/.test(jiraKey)) fail('--jira-key must be letters/digits, for example ACME');
// The stack becomes a folder name, and every other preset folder is deleted later: it must be a plain name inside presets/.
if (!/^[a-z0-9-]+$/.test(stack)) fail(`--stack must be a plain preset name (lowercase letters, digits, -), got "${stackArg}"`);
const presetDir = path.join(root, 'presets', stack);
if (path.relative(path.join(root, 'presets'), presetDir).startsWith('..')) fail('--stack resolves outside presets/');
if (!existsSync(path.join(presetDir, 'preset.json'))) {
  const have = existsSync(path.join(root, 'presets')) ? readdirSync(path.join(root, 'presets')).filter((d) => existsSync(path.join(root, 'presets', d, 'preset.json'))) : [];
  fail(`unknown stack "${stackArg}". Available: ${have.join(', ') || '(none)'}`);
}
const stateFile = path.join(root, '.claude', 'spec-driven', 'init.json');
if (existsSync(stateFile) && !force) fail(`already initialised (${path.relative(root, stateFile)}). Use --force to run again; existing files are kept unless they are generated by this script.`);

// Parse every JSON file we will touch before writing anything, so a malformed file stops init with a clear message
// instead of leaving a half-initialised repo.
const parseJson = (file) => {
  try {
    return JSON.parse(readFileSync(file, 'utf8'));
  } catch (e) {
    return fail(`${path.relative(root, file).split(path.sep).join('/')} is not valid JSON (${e.message}). Fix it, then run init again.`);
  }
};
const preset = parseJson(path.join(presetDir, 'preset.json'));
const cfgFile = path.join(root, '.claude', 'hooks.config.json');
const setFile = path.join(root, '.claude', 'settings.json');
const curCfg = existsSync(cfgFile) ? parseJson(cfgFile) : {};
const curSettings = existsSync(setFile) ? parseJson(setFile) : null;
const log = [];
const note = (m) => log.push(m);
const write = (file, text) => {
  note(`write  ${path.relative(root, file).split(path.sep).join('/')}`);
  if (dry) return;
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, text);
};
const readText = (f) => readFileSync(f, 'utf8');

// 1. variables
const today = new Date().toISOString().slice(0, 10);
const FILL = '_(fill in)_';
const vars = {
  PROJECT_NAME: name,
  ONE_LINE_DESCRIPTION: opt('description', '_(one line: what the product does and for whom)_'),
  JIRA_KEY: jiraKey,
  JIRA_KEY_LOWER: jiraKey.toLowerCase(),
  DEFAULT_BRANCH: opt('default-branch', 'main'),
  ROADMAP_DOC: opt('roadmap', FILL),
  DATE: today,
  INSTALL_COMMAND: opt('install', preset.commands?.INSTALL_COMMAND ?? FILL),
  BUILD_COMMAND: opt('build', preset.commands?.BUILD_COMMAND ?? FILL),
  LINT_COMMAND: opt('lint', preset.commands?.LINT_COMMAND ?? FILL),
  TEST_COMMAND: opt('test', preset.commands?.TEST_COMMAND ?? FILL),
  VERIFY_COMMAND: opt('verify', preset.commands?.VERIFY_COMMAND ?? FILL),
};
const fill = (text) => text.replace(/\{\{([A-Z_]+)\}\}/g, (m, k) => (k in vars ? vars[k] : m));

// 2. copy preset files (never overwrite an existing file)
const filesDir = preset.filesDir ? path.join(presetDir, preset.filesDir) : null;
// A source file named _dot_<name> is installed as .<name> (the same trick npm uses for _gitignore). It lets a preset ship
// .env.example without a tool that blocks every .env.* path (including this repo's own permission rules) tripping on it.
function copyTree(from, to) {
  for (const n of readdirSync(from)) {
    const s = path.join(from, n);
    const d = path.join(to, n.startsWith('_dot_') ? `.${n.slice(5)}` : n);
    if (statSync(s).isDirectory()) copyTree(s, d);
    else if (existsSync(d)) note(`keep   ${path.relative(root, d).split(path.sep).join('/')} (exists)`);
    else write(d, readText(s));
  }
}
if (filesDir && existsSync(filesDir)) copyTree(filesDir, root);

// 3. hooks config: merge the preset values into the current file. Arrays (policyFiles, immutableDirs, stopGate.checks ...)
// are united, never replaced, so protection the project already has is not dropped; objects merge key by key; a plain
// value from the preset replaces the current one.
const isObj = (v) => v && typeof v === 'object' && !Array.isArray(v);
function mergeConfig(cur, add) {
  const out = { ...cur };
  for (const [k, v] of Object.entries(add)) {
    if (Array.isArray(v) && Array.isArray(cur[k])) {
      const seen = new Set(cur[k].map((x) => JSON.stringify(x)));
      out[k] = [...cur[k], ...v.filter((x) => !seen.has(JSON.stringify(x)))];
    } else if (isObj(v) && isObj(cur[k])) out[k] = mergeConfig(cur[k], v);
    else out[k] = v;
  }
  return out;
}
if (preset.hooksConfig && Object.keys(preset.hooksConfig).length) {
  write(cfgFile, `${JSON.stringify(mergeConfig(curCfg, preset.hooksConfig), null, 2)}\n`);
}

// 4. settings: add allow patterns
if (preset.settingsAllow?.length && curSettings) {
  const s = curSettings;
  s.permissions ??= {};
  s.permissions.allow = [...new Set([...(s.permissions.allow ?? []), ...preset.settingsAllow])];
  write(setFile, `${JSON.stringify(s, null, 2)}\n`);
}

// 5. upstream manifest: append the preset's lines
const manifest = path.join(root, '.claude', 'spec-driven', 'upstream.sha256');
if (preset.upstreamManifest && existsSync(path.join(presetDir, preset.upstreamManifest)) && existsSync(manifest)) {
  const have = new Set(readText(manifest).split(/\r?\n/).filter(Boolean));
  const add = readText(path.join(presetDir, preset.upstreamManifest)).split(/\r?\n/).filter((l) => l && !have.has(l));
  if (add.length) write(manifest, `${[...have, ...add].join('\n')}\n`);
}

// 6. profile
const profile = path.join(root, '.claude', 'project-profile.md');
const tpl = path.join(root, '.claude', 'spec-driven', 'project-profile.template.md');
if (!existsSync(tpl)) fail('missing .claude/spec-driven/project-profile.template.md');
// A profile somebody has already filled in is never overwritten by --force; only --reset-profile does, and the old file
// is kept as project-profile.md.bak.
// "Still a template" means unrendered markers only: a profile that init already rendered always contains _(fill in)_ fields
// until a person completes them, so those must not count as "not yet edited".
const profileStillTemplate = existsSync(profile) && /\{\{[A-Z_]+\}\}|<!-- preset:/.test(readText(profile));
const rewriteProfile = !existsSync(profile) || flag('reset-profile') || (force && profileStillTemplate);
if (!rewriteProfile) note(`keep   .claude/project-profile.md (${existsSync(profile) && force ? 'already filled in; --reset-profile to regenerate' : 'exists'})`);
else {
  const frag = preset.profileFragment && existsSync(path.join(presetDir, preset.profileFragment)) ? readText(path.join(presetDir, preset.profileFragment)).trimEnd() : '';
  const rows = preset.skillMapRows && existsSync(path.join(presetDir, preset.skillMapRows)) ? readText(path.join(presetDir, preset.skillMapRows)).trimEnd() : '';
  // Function replacements: a string replacement would expand $& and $' sequences found in the fragment text.
  let t = readText(tpl)
    .replace('<!-- preset:stack -->\n\n', () => (frag ? `${frag}\n\n` : ''))
    .replace('<!-- preset:stack -->', () => frag)
    .replace('\n<!-- preset:skills -->', () => (rows ? `\n${rows}` : ''));
  // Keep the old profile; never overwrite an earlier backup (a second reset gets a timestamped name).
  if (existsSync(profile)) write(existsSync(`${profile}.bak`) ? `${profile}.${Date.now()}.bak` : `${profile}.bak`, readText(profile));
  write(profile, fill(t));
}

// 7. CLAUDE.md
const claudeMd = path.join(root, 'CLAUDE.md');
if (existsSync(claudeMd)) {
  const cur = readText(claudeMd);
  if (/\{\{[A-Z_]+\}\}/.test(cur)) write(claudeMd, fill(cur));
  else note('keep   CLAUDE.md (no placeholders left)');
}

// 8. folders every spec-driven project needs
for (const d of ['specs', 'docs/todos', 'docs/contracts']) {
  const keep = path.join(root, d, '.gitkeep');
  if (!existsSync(path.join(root, d))) write(keep, '');
}

// 9. state (written before the irreversible step, so a re-run knows init got this far)
write(stateFile, `${JSON.stringify({ name, stack, jiraKey, initialisedOn: today }, null, 2)}\n`);

// 10. remove presets that were not chosen: last, and only plain folders directly under presets/
const presetsRoot = path.join(root, 'presets');
for (const d of readdirSync(presetsRoot)) {
  const p = path.join(presetsRoot, d);
  if (statSync(p).isDirectory() && d !== stack && /^[a-z0-9-]+$/.test(d) && path.dirname(p) === presetsRoot) {
    note(`remove presets/${d} (not chosen)`);
    if (!dry) rmSync(p, { recursive: true, force: true });
  }
}

// report
console.log(`${dry ? '[dry run] ' : ''}Initialised "${name}" with the "${stack}" preset.`);
for (const l of log) console.log(`  ${l}`);
const left = [];
for (const f of [claudeMd, profile]) {
  if (!existsSync(f)) continue;
  const t = readText(f);
  const n = (t.match(/\{\{[A-Z_]+\}\}/g) ?? []).length;
  const fills = (t.match(/_\(fill in\)_|_\(one line:/g) ?? []).length;
  const verifies = (t.match(/\(verify\)/g) ?? []).length;
  if (n || fills || verifies) left.push(`${path.relative(root, f).split(path.sep).join('/')}: ${fills + n} to fill in, ${verifies} marked (verify)`);
}
console.log('\nStill to do by hand:');
for (const l of left.length ? left : ['(nothing flagged)']) console.log(`  - ${l}`);
console.log('  - .claude/project-profile.md §2 (stack facts), §3 (overrides), §5 (integrations); add the project\'s own rules in .claude/rules/');
console.log('  - copy CLAUDE.local.md.example to CLAUDE.local.md; copy .mcp.json.example to .mcp.json only if you need those servers');
console.log('Then run: node scripts/claude/validate-workflow.mjs');
